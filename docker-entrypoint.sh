#!/bin/sh
# Стартуем как root: чиним владельца тома /data (устойчиво к тому, уже созданному под root —
# не требует от пользователя удалять volume), затем сбрасываем привилегии и запускаем агента
# под непривилегированным bun через su-exec.
chown -R bun:bun /data 2>/dev/null || true
exec su-exec bun "$@"
